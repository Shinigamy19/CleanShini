impl Lang {
    pub fn code(&self) -> &'static str {
        match self { Lang::Es => "ES", Lang::En => "EN" }
    }
    pub fn next(self) -> Self {
        match self { Lang::Es => Lang::En, Lang::En => Lang::Es }
    }
}

